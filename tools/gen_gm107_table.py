#!/usr/bin/env python3
"""Convert the envytools GM107 instruction tables into the JSON table the shader
tools read (src/shader/gm107.json).

    python3 tools/gen_gm107_table.py

Input: extern/reference/envytools/gm107.c (MIT licence; see
src/shader/LICENSE-envytools). The C tables are data: for every instruction a bit
pattern, a mask and a list of operand fields. This script turns each field into a
plain description (register at bit N, immediate of W bits, memory operand ...), so
nothing else needs the C file. Run it again only if the reference changes.
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
src = (ROOT / "extern/reference/envytools/gm107.c").read_text()
src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)

bitfields = {m.group(1): [int(m.group(2)), int(m.group(3))]
             for m in re.finditer(r"static struct\s+bitfield (\w+) = \{ (\d+), (\d+)", src)}
xorend = {m.group(1): int(m.group(2)) for m in re.finditer(r"static struct\s+bitfield (\w+) = \{[^}]*\.xorend = (\d+)", src)}
rbit = {}
for m in re.finditer(r"static struct rbitfield (\w+) = \{ \{([^}]*)\}, (RBF_\w+)([^;]*)\};", src):
    nums = [int(x) for x in m.group(2).replace(" ", "").split(",")]
    parts = [[nums[i], nums[i + 1]] for i in range(0, len(nums), 2)]
    extra = m.group(4)
    shl = re.search(r"\.shr = (\d+)", extra)
    rbit[m.group(1)] = {"parts": parts, "signed": m.group(3) == "RBF_SIGNED", "shl": int(shl.group(1)) if shl else 0,
                        "pcrel": ".pcrel" in extra, "addend": int(a.group(1)) if (a := re.search(r"\.addend = (\d+)", extra)) else 0}
regs = {m.group(1): (m.group(2), m.group(3)) for m in re.finditer(r'static struct reg (\w+) = \{ &(\w+), "(\w+)"', src)}
mems = {}
for m in re.finditer(r'static struct mem (\w+) = \{ "(\w+)", (&\w+|0)(?:, (&\w+|0))?(?:, (&\w+|0))? \};', src):
    mems[m.group(1)] = (m.group(2), m.group(3), m.group(4) or "0", m.group(5) or "0")
defines = {m.group(1): (m.group(2), m.group(3)) for m in re.finditer(r"#define (\w+) (atom\w+), &(\w+)", src)}


def atom(tok):
    tok = tok.strip()
    if m := re.match(r'N\(\s*"([^"]*)"\s*\)', tok):
        return {"k": "name", "n": m.group(1)}
    if m := re.match(r'(ON|ZN|ONV|ZNV)\((\d+),\s*"?(\w+)"?', tok):
        return {"k": "flag", "bit": int(m.group(2)), "n": m.group(3), "when": 1 if m.group(1).startswith("O") else 0}
    if m := re.match(r"T\((\w+)\)", tok):
        return {"k": "table", "t": m.group(1)}
    if tok in ("OP8B", "OOPS") or tok.startswith(".fmask"):
        return None
    if tok in defines:
        kind, sym = defines[tok]
        if kind == "atomreg":
            bf, prefix = regs[sym]
            a = {"k": "reg", "p": prefix, "pos": bitfields[bf][0], "w": bitfields[bf][1]}
            if bf in xorend:
                a["xor"] = xorend[bf]
            return a
        if kind in ("atomrimm", "atomctarg"):
            a = dict(rbit[sym], k="target" if kind == "atomctarg" else "imm")
            if tok[0] in "FD":
                a["float"] = 32 if tok[0] == "F" else 64
            return a
        if kind == "atommem":
            name, idx, reg, imm = mems[sym]
            a = {"k": "mem", "n": name}
            if idx != "0":
                a["idx"] = bitfields[idx[1:]]
            if reg != "0":
                bf, _ = regs[reg[1:]]
                a["reg"] = bitfields[bf][0]
            if imm != "0":
                a["imm"] = rbit[imm[1:]]
            return a
    return {"k": "raw", "n": tok}


def split(row):
    out, depth, cur = [], 0, ""
    for ch in row:
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    return out + [cur] if cur.strip() else out


tables = {}
for m in re.finditer(r"static struct insn tab(\w+)\[\] = \{(.*?)\n?\};", src, re.S):
    rows = []
    for r in re.finditer(r"\{\s*(0x[0-9a-f]+ull|0)\s*,\s*(0x[0-9a-f]+ull|0)\s*(?:,(.*?))?\}\s*,?\s*(?=\{|$)", m.group(2), re.S):
        atoms = [a for a in (atom(t) for t in split(r.group(3) or "")) if a]
        rows.append({"v": int(r.group(1).replace("ull", ""), 16), "m": int(r.group(2).replace("ull", ""), 16), "a": atoms})
    tables[m.group(1)] = rows
out = ROOT / "src/shader/gm107.json"
out.write_text(json.dumps({"source": "envytools envydis/gm107.c (MIT); generated by tools/gen_gm107_table.py",
                           "tables": tables}, separators=(",", ":")))
raw = sorted({a["n"] for rows in tables.values() for r in rows for a in r["a"] if a["k"] == "raw"})
print(f"{len(tables)} tables, {len(tables['root'])} instruction forms -> {out} ({out.stat().st_size // 1024} KB)")
print("fields not understood:", raw)
