#!/usr/bin/env python3
"""Write the Vorbis setup packets that FMOD keeps inside the game's executable as C data.

The game's sample banks (FSB) store Vorbis sound without the "setup" packet a decoder
needs first; each bank names the setup it was encoded with by a 32-bit identifier, and
FMOD looks the packet up in a table built into the executable. This reads that table.
Nothing here is kept in the repository: the output goes to the build directory.

    extract_vorbis_setups.py game/exefs/main out.c
"""
import pathlib
import struct
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from extract_data import Program


def main():
    exe, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    p = Program(exe)
    start, data = p.data
    setups = {}
    # A table entry begins: pointer to the packet, its size, its identifier.
    for addr, (_, _, target) in sorted(p.rel.items()):
        if not (start <= addr < start + len(data) - 16) or p.read(target, 7) != b"\x05vorbis":
            continue
        size, ident = struct.unpack_from("<II", p.read(addr + 8, 8))
        if ident > 0xFFFF and 0 < size < 0x10000:
            setups.setdefault(ident, p.read(target, size))
    if not setups:
        sys.exit("no Vorbis setup packets found in " + str(exe))
    lines = ["/* Generated by tools/extract_vorbis_setups.py from the game dump. Not for the repository. */", ""]
    for n, (ident, blob) in enumerate(sorted(setups.items())):
        lines.append(f"static const unsigned char setup_{n}[] = {{")
        for i in range(0, len(blob), 24):
            lines.append("    " + ",".join(str(b) for b in blob[i:i + 24]) + ",")
        lines.append("};")
    lines.append("const struct { unsigned id, size; const unsigned char * data; } d3_vorbis_setups[] = {")
    for n, (ident, blob) in enumerate(sorted(setups.items())):
        lines.append(f"    {{0x{ident:08x}u, {len(blob)}, setup_{n}}},")
    lines.append("};")
    lines.append(f"const unsigned d3_vorbis_setup_count = {len(setups)};")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"{len(setups)} Vorbis setup packets -> {out}")


if __name__ == "__main__":
    main()
