#!/usr/bin/env python3
"""Generate the default entry points of the do-nothing graphics driver.

The game asks the Switch's graphics driver (NVN) for about 500 functions by name.
This writes one do-nothing function for each, returning a harmless default for
its return type (true for booleans, zero or null otherwise), and a table from name
to function. Names and return types are read from the decomp's NVN header.
Functions that need real behaviour are written by hand in src/gfx/null/ and take
precedence over these defaults.

    python3 tools/gen_nvn_null.py <decomp root> <output.c>
"""
import re, sys
from pathlib import Path

root, out = Path(sys.argv[1]), Path(sys.argv[2])
inc = root / "src/NintendoSDK/Include/nvn"
types = {}
for m in re.finditer(r"^typedef\s+(.*?)\s*\(\*\s*(\w+Func)\s*\)", (inc / "nvn_Cpp.h").read_text(), re.M):
    types[m.group(2)] = m.group(1).strip()
entries = re.findall(r"=\s*\((\w+Func)\)\s*getProc\(device,\s*\"(nvn\w+)\"\)", (inc / "nvn_CppFuncPtrImpl.h").read_text())
if len(entries) < 100:
    sys.exit("gen_nvn_null: could not read the entry-point list from the decomp's NVN header")

L = ["// Generated by tools/gen_nvn_null.py. Do not edit.",
     '#include "gfx/null/nvn_null.h"', ""]
table = []
for ftype, name in entries:
    ret = types.get(ftype, "void")
    if ret == "void":
        c, body = "void", ""
    elif ret == "float":
        c, body = "float", " return 0.0f;"
    elif ret == "NVNboolean":
        c, body = "int", " return 1;"
    else:
        c, body = "unsigned long", " return 0;"
    L.append(f'static {c} n_{name}(void) {{ d3_nvn_called("{name}");{body} }}')
    table.append(f'    {{"{name}", (d3_nvn_function)n_{name}}},')
L += ["", "const struct d3_nvn_entry d3_nvn_defaults[] = {"] + table + ["    {0, 0}", "};"]
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(L) + "\n")
